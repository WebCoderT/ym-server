/**
 * 访问级别枚举模块
 *
 * 本模块定义了系统中所有受支持的用户角色访问级别。
 * 访问级别用于区分不同用户群体对接口的访问权限，是权限控制体系的核心枚举。
 *
 * @module access-level.enum
 */

/**
 * 访问级别枚举
 *
 * 该枚举定义了三种系统角色：
 * - ADMIN: 后台管理员，拥有最高权限，可访问管理后台接口
 * - CLIENT: 客户端用户，即普通 C 端用户，可访问小程序或 App 接口
 * - PUBLIC: 公开访问者，无需登录即可访问的公共接口
 *
 * 在 JWT 令牌中，role 字段的值必须与该枚举中的某个值匹配，否则令牌将被视为无效。
 */
export enum AccessLevel {
  /** 后台管理员角色，对应管理后台的所有接口权限 */
  ADMIN = 'admin',
  /** 客户端用户角色，对应 C 端业务接口权限 */
  CLIENT = 'client',
  /** 公开访问角色，对应无需鉴权的公共接口 */
  PUBLIC = 'public',
}
